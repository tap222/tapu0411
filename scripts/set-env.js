const fs = require('fs');
const path = require('path');
const dotenv = require('dotenv');

// Load environment variables from .env
const envPath = path.resolve(__dirname, '../.env');
if (fs.existsSync(envPath)) {
  dotenv.config({ path: envPath });
} else {
  dotenv.config();
}

const targetDir = path.resolve(__dirname, '../src/environments');
if (!fs.existsSync(targetDir)) {
  fs.mkdirSync(targetDir, { recursive: true });
}

const createEnvFile = (isProd) => {
  return `// Auto-generated by scripts/set-env.js - Do not edit directly
export const environment = {
  production: ${isProd},
  pokeApiGraphqlUrl: '${process.env.POKEAPI_GRAPHQL_URL || 'https://beta.pokeapi.co/graphql/v1beta'}',
  backendGraphqlUrl: '${process.env.BACKEND_GRAPHQL_URL || 'http://localhost:4000/graphql'}',
  cacheTtlMs: ${Number(process.env.CACHE_TTL_MS) || 600000},
  requestTimeoutMs: ${Number(process.env.REQUEST_TIMEOUT_MS) || 30000},
  imageCacheDurationMs: ${Number(process.env.IMAGE_CACHE_DURATION_MS) || 600000},
  imageCacheMaxRetries: ${Number(process.env.IMAGE_CACHE_MAX_RETRIES) || 3},
  imageCacheRetryDelayMs: ${Number(process.env.IMAGE_CACHE_RETRY_DELAY_MS) || 1000},
  defaultPageSize: ${Number(process.env.DEFAULT_PAGE_SIZE) || 25},
};
`;
};

fs.writeFileSync(path.join(targetDir, 'environment.ts'), createEnvFile(false));
fs.writeFileSync(path.join(targetDir, 'environment.prod.ts'), createEnvFile(true));
console.log('✓ Angular environment files successfully generated from .env');
